def build_user_prompt(jd_text, resume_text):
    """生成发送给模型的用户提示词。"""
    return f"""
请根据下面的岗位 JD 和基础简历，分析候选人与岗位的匹配情况。

岗位 JD：
{jd_text}

基础简历：
{resume_text}
""".strip()
